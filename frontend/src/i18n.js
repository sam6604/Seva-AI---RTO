// Static UI-chrome translations — labels, buttons, headers. Separate from
// the AI's actual chat replies, which are translated live by the backend
// (Sarvam) per-turn. This file only covers fixed strings that exist
// regardless of what the user says, so the whole app (not just the chat)
// changes language the moment they pick one on the language screen.
//
// Keeping this to 4 languages (en/hi/te/or) per request — the chat itself
// still supports every language Sarvam does, this only limits which
// languages have a fully-translated app shell.

export const UI_LANGUAGES = [
  { code: 'hi-IN', uiLang: 'hi', label: 'हिन्दी' },
  { code: 'te-IN', uiLang: 'te', label: 'తెలుగు' },
  { code: 'od-IN', uiLang: 'or', label: 'ଓଡ଼ିଆ' },
  { code: 'en-IN', uiLang: 'en', label: 'English' },
]

export function uiLangFor(bcp47) {
  return UI_LANGUAGES.find((l) => l.code === bcp47)?.uiLang || 'en'
}

